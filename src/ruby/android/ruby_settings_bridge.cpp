// ── Zypher look ──────────────────────────────────────────────────────────────
// Mirrors RubyQuickViewport's get/setZypherLook call-for-call (same keys, same
// "empty / negative means leave it alone" semantics) so MeshStyleBar can be
// hosted here in the Ground Mesh Studio exactly as it is in the in-scene
// editor, and both persist into the SAME QSettings keys the viewport reads.
bool RubySettingsBridge::zypherActive() const {
    return groundGenerator() == QStringLiteral("zypher");
}

QVariantMap RubySettingsBridge::getZypherLook() const {
    QSettings s;
    QVariantMap out;
    out[QStringLiteral("active")] = zypherActive();
    out[QStringLiteral("hatStyle")] =
        s.value(QStringLiteral("ruby_mobile/zypher_hat"),
                QLatin1String(zypher_look::kDefaultHatStyle)).toString();
    out[QStringLiteral("topStyle")] =
        s.value(QStringLiteral("ruby_mobile/zypher_top"),
                QLatin1String(zypher_look::kDefaultTopStyle)).toString();
    out[QStringLiteral("frequency")] =
        s.value(QStringLiteral("ruby_mobile/zypher_freq"),
                zypher_look::kDefaultFrequency).toDouble();
    out[QStringLiteral("depth")] =
        s.value(QStringLiteral("ruby_mobile/zypher_depth"),
                zypher_look::kDefaultDepth).toDouble();
    out[QStringLiteral("minCollisionRadius")] =
        s.value(QStringLiteral("ruby_mobile/zypher_mincoll"),
                zypher_look::kDefaultMinColl).toDouble();
    return out;
}

void RubySettingsBridge::setZypherLook(const QString& hatStyle, const QString& topStyle,
                                       float frequency, float depth,
                                       float minCollisionRadius) {
    QSettings s;
    if (!hatStyle.trimmed().isEmpty())
        s.setValue(QStringLiteral("ruby_mobile/zypher_hat"), hatStyle.trimmed());
    if (!topStyle.trimmed().isEmpty())
        s.setValue(QStringLiteral("ruby_mobile/zypher_top"), topStyle.trimmed());
    if (frequency > 0.0f)
        s.setValue(QStringLiteral("ruby_mobile/zypher_freq"), double(frequency));
    if (depth >= 0.0f)
        s.setValue(QStringLiteral("ruby_mobile/zypher_depth"), double(depth));
    if (minCollisionRadius >= 0.0f)
        s.setValue(QStringLiteral("ruby_mobile/zypher_mincoll"),
                   double(minCollisionRadius));
    s.sync();
}

QVariantList RubySettingsBridge::customMeshPresets() const {
    QSettings s;
    QByteArray data = s.value(QStringLiteral("ruby_mobile/custom_mesh_presets")).toByteArray();
    if (data.isEmpty()) return QVariantList();
    QJsonDocument doc = QJsonDocument::fromJson(data);
    return doc.array().toVariantList();
}

void RubySettingsBridge::saveCustomMeshPreset(const QString& name, const QString& topTex, const QString& groundTex) {
    QVariantList list = customMeshPresets();
    // Check if duplicate exists with same top & ground, if so replace name
    bool found = false;
    for (int i = 0; i < list.size(); ++i) {
        QVariantMap m = list[i].toMap();
        if (m.value("top").toString() == topTex && m.value("ground").toString() == groundTex) {
            m["name"] = name.isEmpty() ? (topTex + " / " + groundTex) : name;
            list[i] = m;
            found = true;
            break;
        }
    }
    if (!found) {
        QVariantMap item;
        item["name"] = name.isEmpty() ? (topTex + " / " + groundTex) : name;
        item["top"] = topTex;
        item["ground"] = groundTex;
        list.append(item);
    }
    QJsonArray arr = QJsonArray::fromVariantList(list);
    QSettings s;
    s.setValue(QStringLiteral("ruby_mobile/custom_mesh_presets"), QJsonDocument(arr).toJson(QJsonDocument::Compact));
    emit customMeshPresetsChanged();
}

void RubySettingsBridge::deleteCustomMeshPreset(int index) {
    QVariantList list = customMeshPresets();
    if (index >= 0 && index < list.size()) {
        list.removeAt(index);
        QJsonArray arr = QJsonArray::fromVariantList(list);
        QSettings s;
        s.setValue(QStringLiteral("ruby_mobile/custom_mesh_presets"), QJsonDocument(arr).toJson(QJsonDocument::Compact));
        emit customMeshPresetsChanged();
    }
}

